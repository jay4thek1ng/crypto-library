#!/usr/bin/env node
/**
 * Build the mobile catalog from the web library without modifying those files.
 *
 * Reads ../data.js, ../config.js, ../covers and ../pdfjs.
 * Writes src/data/catalog.json, src/data/covers.ts, src/data/backend.json,
 * src/data/reader-assets.ts, and copies covers plus the PDF.js reader assets.
 *
 * PDFs are not copied. The catalog points at the copies already hosted with the web app.
 */
import fs from 'fs';
import path from 'path';
import vm from 'vm';
import { Buffer } from 'node:buffer';
import { fileURLToPath } from 'url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(mobileRoot, '..');

function readWindowScript(rel) {
  const code = fs.readFileSync(path.join(repoRoot, rel), 'utf8');
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(code, context, { filename: rel });
  return context.window;
}

function assertAnonKey(key) {
  const parts = String(key).split('.');
  if (parts.length !== 3) throw new Error('Supabase key in config.js is not a JWT');
  const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
  if (payload.role !== 'anon') {
    throw new Error(`Refusing to embed a Supabase key with role "${payload.role}". Only the anon key is allowed.`);
  }
}

function ident(id) {
  const cleaned = id.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned;
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const buf = fs.readFileSync(src);
  if (fs.existsSync(dest) && fs.statSync(dest).size === buf.length) return;
  fs.writeFileSync(dest, buf);
}

function copyTree(srcDir, destDir) {
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const src = path.join(srcDir, entry.name);
    const dest = path.join(destDir, entry.name);
    if (entry.isDirectory()) copyTree(src, dest);
    else if (entry.isFile()) copyFile(src, dest);
  }
}

const data = readWindowScript('data.js');
const config = readWindowScript('config.js');
const library = data.LIBRARY;
const wp = config.WP_CONFIG;
if (!Array.isArray(library) || library.length === 0) throw new Error('data.js did not define window.LIBRARY');
if (!wp || !wp.supabaseUrl || !wp.supabaseAnonKey) throw new Error('config.js is missing the public Supabase config');
assertAnonKey(wp.supabaseAnonKey);

const coversDir = path.join(mobileRoot, 'assets', 'covers');
fs.mkdirSync(coversDir, { recursive: true });
const catalog = [];
for (const book of library) {
  const id = String(book.id);
  let cover = null;
  if (typeof book.cover === 'string' && book.cover) {
    const src = path.join(repoRoot, book.cover);
    if (fs.existsSync(src)) {
      copyFile(src, path.join(coversDir, `${id}.webp`));
      cover = id;
    }
  }
  catalog.push({
    id,
    title: book.title,
    project: book.project,
    ticker: book.ticker ?? '',
    authors: book.authors ?? '',
    year: book.year ?? 0,
    cat: book.cat,
    tags: Array.isArray(book.tags) ? book.tags : [],
    summary: book.summary ?? '',
    url: book.url ?? '',
    kind: book.kind ?? '',
    local: book.local ?? '',
    localKind: book.localKind ?? '',
    cover,
  });
}

fs.mkdirSync(path.join(mobileRoot, 'src', 'data'), { recursive: true });
fs.writeFileSync(path.join(mobileRoot, 'src', 'data', 'catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);

const coverImports = catalog.filter((book) => book.cover).map((book) => {
  const name = `cover_${ident(book.id)}`;
  return { name, id: book.id, line: `import ${name} from '../../assets/covers/${book.id}.webp';` };
});
const coversTs = `// @ts-nocheck
/* eslint-disable */
// Generated by scripts/generate-catalog.mjs. Do not edit by hand.
${coverImports.map((row) => row.line).join('\n')}

export const COVERS: Record<string, number> = {
${coverImports.map((row) => `  ${JSON.stringify(row.id)}: ${row.name},`).join('\n')}
};
`;
fs.writeFileSync(path.join(mobileRoot, 'src', 'data', 'covers.ts'), coversTs);

fs.writeFileSync(
  path.join(mobileRoot, 'src', 'data', 'backend.json'),
  `${JSON.stringify({ supabaseUrl: String(wp.supabaseUrl).replace(/\/+$/, ''), supabaseAnonKey: wp.supabaseAnonKey }, null, 2)}\n`,
);

const readerDir = path.join(mobileRoot, 'assets', 'reader');
fs.mkdirSync(readerDir, { recursive: true });
copyFile(path.join(repoRoot, 'pdfjs', 'pdf.min.mjs'), path.join(readerDir, 'pdf.min.mjs'));
copyFile(path.join(repoRoot, 'pdfjs', 'pdf.worker.min.mjs'), path.join(readerDir, 'pdf.worker.min.mjs'));
copyFile(path.join(repoRoot, 'pdfjs', 'LICENSE.txt'), path.join(readerDir, 'LICENSE.txt'));
copyTree(path.join(repoRoot, 'pdfjs', 'standard_fonts'), path.join(readerDir, 'standard_fonts'));
copyTree(path.join(repoRoot, 'pdfjs', 'cmaps'), path.join(readerDir, 'cmaps'));

const READER_EXTENSIONS = new Set(['.mjs', '.html', '.bcmap', '.ttf', '.pfb']);

function walk(dir, prefix = '') {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...walk(path.join(dir, entry.name), rel));
    else if (entry.isFile() && READER_EXTENSIONS.has(path.extname(entry.name))) files.push(rel);
  }
  return files.sort();
}

const bundleDir = path.join(mobileRoot, 'assets', 'reader-bundle');
fs.mkdirSync(bundleDir, { recursive: true });
const readerFiles = walk(readerDir);
const readerImports = readerFiles.map((rel, i) => {
  const name = `asset_${i}`;
  let from = `../../assets/reader/${rel}`;
  if (rel.endsWith('.mjs')) {
    const binName = `${path.basename(rel, '.mjs')}.bin`;
    copyFile(path.join(readerDir, rel), path.join(bundleDir, binName));
    from = `../../assets/reader-bundle/${binName}`;
  }
  return { name, rel, line: `import ${name} from '${from}';` };
});
const readerTs = `// @ts-nocheck
/* eslint-disable */
// Generated by scripts/generate-catalog.mjs. Do not edit by hand.
${readerImports.map((row) => row.line).join('\n')}

export const READER_FILES: { path: string; moduleId: number }[] = [
${readerImports.map((row) => `  { path: ${JSON.stringify(row.rel)}, moduleId: ${row.name} },`).join('\n')}
];
`;
fs.writeFileSync(path.join(mobileRoot, 'src', 'data', 'reader-assets.ts'), readerTs);

const publicReader = path.join(mobileRoot, 'public', 'reader');
fs.mkdirSync(path.join(mobileRoot, 'public'), { recursive: true });
// A symlink keeps one copy of PDF.js for Expo web (public/) and the native asset bundle.
try {
  const stat = fs.lstatSync(publicReader);
  if (!stat.isSymbolicLink()) fs.rmSync(publicReader, { recursive: true, force: true });
} catch {
  // absent
}
if (!fs.existsSync(publicReader)) fs.symlinkSync(path.relative(path.dirname(publicReader), readerDir), publicReader);

const withPdf = catalog.filter((book) => book.localKind === 'pdf' || String(book.local).endsWith('.pdf') || /\.pdf(?:$|[?#])/i.test(book.url)).length;
console.log(`Catalog: ${catalog.length} papers, ${coverImports.length} covers, ${withPdf} direct PDFs, ${readerFiles.length} reader files.`);
